function renderApprovedReviews(reviews) {
  if (!approvedReviewsGrid || !Array.isArray(reviews) || !reviews.length) return;

  approvedReviewsGrid.innerHTML = "";

  reviews.slice(0, 9).forEach(({ name = "Guest", rating = 5, review = "" }) => {
    const cleanReview = review.trim();
    if (!cleanReview) return;
    const cleanRating = Math.max(1, Math.min(5, Number(rating) || 5));
    const stars = "★".repeat(cleanRating) + "☆".repeat(5 - cleanRating);

    const card = document.createElement("figure");
    card.className = "approved-review-card";

    const starsElement = document.createElement("div");
    starsElement.className = "approved-review-stars";
    starsElement.textContent = stars;

    const quote = document.createElement("blockquote");
    quote.textContent = `“${cleanReview}”`;

    const caption = document.createElement("figcaption");
    caption.textContent = `— ${name}`;

    card.append(starsElement, quote, caption);
    approvedReviewsGrid.append(card);
  });
}

