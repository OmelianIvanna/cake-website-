function softenFeaturedCarouselEdges() {
  if (!featuredCarousels.length || window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;

  featuredCarousels.forEach((carousel) => {
    const carouselBox = carousel.getBoundingClientRect();
    const carouselCenter = carouselBox.left + carouselBox.width / 2;
    const edgeDistance = carouselBox.width / 2;

    carousel.querySelectorAll(".featured-cakes-track img").forEach((image) => {
      const imageBox = image.getBoundingClientRect();
      const imageCenter = imageBox.left + imageBox.width / 2;
      const distance = Math.min(Math.abs(carouselCenter - imageCenter) / edgeDistance, 1);
      const closeness = 1 - distance;
      const scale = 0.92 + closeness * 0.09;
      const opacity = 0.72 + closeness * 0.28;

      image.style.setProperty("--featured-scale", scale.toFixed(3));
      image.style.setProperty("--featured-opacity", opacity.toFixed(3));
    });
  });

  window.requestAnimationFrame(softenFeaturedCarouselEdges);
}

