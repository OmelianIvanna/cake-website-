function markLastFlavourCategory() {
  const lastCategory = localStorage.getItem("bratislavaCakesLastFlavourCategory");

  document.querySelectorAll(".flavour-category").forEach((category) => {
    const categoryPage = category.getAttribute("href");
    if (!categoryPage) return;

    const isLastVisited = categoryPage === lastCategory;
    category.classList.toggle("last-visited", isLastVisited);

    category.addEventListener("click", () => {
      localStorage.setItem("bratislavaCakesLastFlavourCategory", categoryPage);
    });
  });
}

